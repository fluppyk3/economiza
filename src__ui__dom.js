export function icon(name, { size = 22, label = null } = {}) {
  const span = document.createElement('span');
  span.className = 'icon';
  span.setAttribute('aria-hidden', label ? 'false' : 'true');
  if (label) span.setAttribute('role', 'img'), span.setAttribute('aria-label', label);
  // Constante interna do aplicativo — nunca dados do usuário.
  span.innerHTML = `<svg viewBox="0 0 24 24" width="${size}" height="${size}" fill="none" stroke="currentColor" stroke-width="1.9" stroke-linecap="round" stroke-linejoin="round" focusable="false">${ICONS[name] ?? ''}</svg>`;
  return span;
}

const dtDate = new Intl.DateTimeFormat('pt-BR', { day: '2-digit', month: '2-digit', year: 'numeric' });
const dtTime = new Intl.DateTimeFormat('pt-BR', { hour: '2-digit', minute: '2-digit' });

export function fmtDate(iso) { const d = new Date(iso); return Number.isNaN(d.getTime()) ? '—' : dtDate.format(d); }
export function fmtDateTime(iso) { const d = new Date(iso); return Number.isNaN(d.getTime()) ? '—' : `${dtDate.format(d)} ${dtTime.format(d)}`; }

/** "há 3 dias" / "hoje" */
export function fmtAgo(iso, nowIso = new Date().toISOString()) {
  const days = Math.floor((Date.parse(nowIso) - Date.parse(iso)) / 86_400_000);
  if (!Number.isFinite(days)) return '';
  if (days <= 0) return 'hoje';
  if (days === 1) return 'ontem';
  if (days < 30) return `há ${days} dias`;
  const m = Math.floor(days / 30);
  return m < 12 ? `há ${m} ${m === 1 ? 'mês' : 'meses'}` : `há ${Math.floor(m / 12)} ano(s)`;
}

export function debounce(fn, ms = 200) {
  let t;
  const d = (...a) => { clearTimeout(t); t = setTimeout(() => fn(...a), ms); };
  d.cancel = () => clearTimeout(t);
  return d;
}

/** Baixa um texto/JSON como arquivo. */
export function downloadFile(filename, content, mime) {
  const blob = new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url; a.download = filename;
  document.body.appendChild(a); a.click(); a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 2000);
}
